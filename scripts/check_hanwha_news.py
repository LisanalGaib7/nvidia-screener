"""
한화엔진 수주·계약 뉴스 감지 — Google News RSS (국내 언론 위주)
한화엔진의 신규 수주, 계약, 파트너십, 수출 뉴스를 감지해 Telegram 알림.

locale="ko" → 국내 언론사(연합뉴스·조선비즈·매일경제·한국경제 등) 우선 수집.
수집·필터·포맷 로직은 news_monitor.py 공용 코어에 있음 — 여기는 설정만.
"""
from news_monitor import MonitorConfig, run_monitor

# Google News 검색 쿼리 — 갈래 분할 (check_news.py와 같은 모양).
#
# 예전 쿼리는 따옴표 구("한화엔진 수주" …)의 OR 체인이었는데, 한글 따옴표 구는
# 구로 묶이지 않고 낱말로 풀린다. 실측(2026-10-10): 100건(상한) 전부 최근 3일치
# 한화 야구단 기사, 제목에 '한화엔진'이 든 기사 0건 — 9/11 이후 발송 0건의 원인.
# 괄호 그룹 갈래로 바꾸면 when:이 먹고 한화엔진 기사가 들어온다(30일 43건).
#
# when:3d — 수집 창은 직전 실행 기준이고 최대 72h(WINDOW_MAX_HOURS)다. 2d면 한 회차를
# 거른 다음 날 48~72h 구간이 빈다. 7일치 수집이 갈래별 57/28/54건이라 3d도 상한 아래.
_WHEN = " when:3d"
QUERIES = [f"한화엔진 ({' OR '.join(terms)}){_WHEN}" for terms in [
    ["수주", "계약", "공급", "납품", "수출", "협약"],
    ["MOU", "업무협약", "파트너십", "협력", "선정", "체결"],
    ["개발", "엔진", "선박", "암모니아", "메탄올", "LNG"],
]]

# 종목 가드는 subject로, 사건어는 낱말로 따로 본다. 예전엔 "한화엔진 계약"처럼
# 붙은 구라서 "한화엔진, 中 조선소向 선박엔진 계약액 12억 상향" 같은 제목을 못 맞췄다.
SUBJECT = ["한화엔진"]
POSITIVE = [
    # 수주·계약
    "수주", "계약", "공급", "납품", "수출", "협약",
    # MOU·파트너십
    "mou", "업무협약", "파트너십", "협력", "선정", "체결",
    # 제품·개발. "엔진"·"선박"은 뺐다 — 사명과 '선박엔진'에 늘 들어 있어 게이트가 안 된다.
    "개발", "암모니아", "메탄올", "lng",
]
NEGATIVE = [
    # 장르 표지 — 시황·리포트·인사 기사. 사명 위치와 무관하게 거른다.
    "특징주", "핫종목", "인기검색", "마감", "강세", "약세", "급등", "급락",
    "주가", "목표가", "투자의견", "매수", "공매도", "[인사]", "임원인사",
    # 재무 낱말은 사명 접두를 유지한다 — 공급계약 기사 제목에 "매출액 대비 N%"가
    # 흔해서 접두 없이 막으면 진짜 계약 기사가 빠진다. "상향/하향"도 같은 이유로 뺐다
    # (실제 계약 정정 기사 제목이 "계약액 12억 상향").
    "한화엔진 주식", "한화엔진 실적", "한화엔진 배당",
    "한화엔진 영업이익", "한화엔진 매출", "한화엔진 순이익",
    "사는 한화엔진", "파는 한화엔진",
]

CONFIG = MonitorConfig(
    query=QUERIES[0], queries=QUERIES, subject=SUBJECT,
    positive=POSITIVE, negative=NEGATIVE,
    header="🟠 <b>한화엔진 수주·계약 뉴스</b>",
    footer="👉 포트폴리오 동향 확인",
    state_file="data/hanwha_news_state.json",
    out_file="hanwha_news_alert.txt",
    locale="ko", label="hanwha-news monitor",
)

if __name__ == "__main__":
    run_monitor(CONFIG)
